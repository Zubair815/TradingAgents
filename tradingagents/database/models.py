class TradeJournalRecord(BaseModel):
    """Persistent representation of an executed trade in the Forex journal."""

    trade_id: str = Field(default_factory=lambda: f"trd_{uuid.uuid4().hex[:12]}")
    proposal_id: str | None = None
    pair: str
    action: ForexAction
    status: TradeStatus = TradeStatus.OPEN
    open_time_utc: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat()
    )
    close_time_utc: str | None = None
    open_price: float
    close_price: float | None = None
    stop_loss: float
    take_profit: float | None = None
    lots: float
    commission: float = 0.0
    swap: float = 0.0
    gross_profit: float | None = None
    net_profit: float | None = None
    pips_gained: float | None = None
    r_multiple: float | None = None
    confidence: float | None = None
    exit_reason: TradeExitReason | None = None
    notes: str = ""
    reflection: str = ""
    tags: list[str] = Field(default_factory=list)
    metadata: dict[str, Any] = Field(default_factory=dict)

    @property
    def is_closed(self) -> bool:
        return self.status == TradeStatus.CLOSED

    @property
    def is_winner(self) -> bool:
        return self.net_profit is not None and self.net_profit > 0.0


