class ProposalRecord(BaseModel):
    """Persistent database representation of a ForexTraderProposal."""

    proposal_id: str = Field(default_factory=lambda: f"prop_{uuid.uuid4().hex[:12]}")
    created_at_utc: str = Field(
        default_factory=lambda: datetime.now(timezone.utc).isoformat()
    )
    pair: str
    action: ForexAction
    order_type: OrderType = OrderType.MARKET
    setup_type: SetupType = SetupType.TREND_CONTINUATION
    timeframe: str = "H1"
    entry_price: float | None = None
    entry_zone_low: float | None = None
    entry_zone_high: float | None = None
    stop_loss: float | None = None
    take_profit_1: float | None = None
    take_profit_2: float | None = None
    risk_reward_ratio: float | None = None
    sl_pips: float | None = None
    tp_pips: float | None = None
    confidence: float | None = None
    suggested_risk_percent: float | None = None
    suggested_lot_size: float | None = None
    confluence_factors: list[str] = Field(default_factory=list)
    invalidation_condition: str | None = None
    reasoning: str = ""
    trade_rationale_summary: str = ""
    status: ProposalStatus = ProposalStatus.PROPOSED
    risk_decision: dict[str, Any] | None = None
    metadata: dict[str, Any] = Field(default_factory=dict)
    schema_version: int = 1
    run_id: str | None = None
    snapshot_id: str | None = None
    version_id: str | None = None
    proposal_payload: dict[str, Any] | None = None
    # Phase 23: Model / Prompt / Strategy Versioning
    provider: str | None = None
    quick_model: str | None = None
    deep_model: str | None = None
    temperature: float | None = None
    reasoning_effort: str | None = None
    max_tokens: int | None = None
    analysts: list[str] = Field(default_factory=list)
    prompt_version: str | None = None
    prompt_hash: str | None = None
    strategy_version: str = "1.0.0"
    system_version: str = "1.0.0"
    data_source_metadata: dict[str, Any] = Field(default_factory=dict)

    def to_forex_trader_proposal(self) -> ForexTraderProposal:
        """Construct domain ForexTraderProposal from database record."""
        if self.proposal_payload is not None:
            p = ForexTraderProposal.model_validate(self.proposal_payload)
            updates: dict[str, Any] = {}
            for f in (
                "provider", "quick_model", "deep_model", "temperature",
                "reasoning_effort", "max_tokens", "analysts", "prompt_version",
                "prompt_hash", "strategy_version", "system_version", "data_source_metadata"
            ):
                if getattr(p, f, None) is None and getattr(self, f, None) is not None:
                    updates[f] = getattr(self, f)
            if updates:
                p = p.model_copy(update=updates)
            return p
        return ForexTraderProposal(
            pair=self.pair,
            action=self.action,
            order_type=self.order_type,
            setup_type=self.setup_type,
            timeframe=self.timeframe,
            entry_price=self.entry_price,
            entry_zone_low=self.entry_zone_low,
            entry_zone_high=self.entry_zone_high,
            stop_loss=self.stop_loss,
            take_profit_1=self.take_profit_1,
            take_profit_2=self.take_profit_2,
            suggested_risk_percent=self.suggested_risk_percent,
            suggested_lot_size=self.suggested_lot_size,
            confluence_factors=self.confluence_factors,
            invalidation_condition=self.invalidation_condition,
            confidence=self.confidence,
            reasoning=self.reasoning,
            trade_rationale_summary=self.trade_rationale_summary,
            provider=self.provider,
            quick_model=self.quick_model,
            deep_model=self.deep_model,
            temperature=self.temperature,
            reasoning_effort=self.reasoning_effort,
            max_tokens=self.max_tokens,
            analysts=list(self.analysts),
            prompt_version=self.prompt_version,
            prompt_hash=self.prompt_hash,
            strategy_version=self.strategy_version,
            system_version=self.system_version,
            data_source_metadata=dict(self.data_source_metadata),
        )

    @property
    def valid_until(self) -> str | None:
        """ISO timestamp until which the trade proposal is valid."""
        if self.metadata:
            return self.metadata.get("valid_until_utc") or self.metadata.get("valid_until")
        return None

    @classmethod
    def from_forex_trader_proposal(
        cls,
        proposal: ForexTraderProposal,
        proposal_id: str | None = None,
        status: ProposalStatus = ProposalStatus.PROPOSED,
        risk_decision: ForexRiskDecision | dict[str, Any] | None = None,
        metadata: dict[str, Any] | None = None,
    ) -> ProposalRecord:
        """Create a ProposalRecord from a domain ForexTraderProposal."""
        pid = proposal_id or f"prop_{uuid.uuid4().hex[:12]}"
        rd_dict: dict[str, Any] | None = None
        if isinstance(risk_decision, ForexRiskDecision):
            rd_dict = risk_decision.model_dump()
        elif isinstance(risk_decision, dict):
            rd_dict = risk_decision

        meta = sanitize_secrets(dict(metadata or {}))
        clean_ds = sanitize_secrets(getattr(proposal, "data_source_metadata", {}) or {})
        if getattr(proposal, "valid_until", None) and "valid_until_utc" not in meta:
            meta["valid_until_utc"] = str(proposal.valid_until)

        # Store versioning in metadata for forward compatibility
        ver_meta = {
            "provider": getattr(proposal, "provider", None),
            "quick_model": getattr(proposal, "quick_model", None),
            "deep_model": getattr(proposal, "deep_model", None),
            "temperature": getattr(proposal, "temperature", None),
            "reasoning_effort": getattr(proposal, "reasoning_effort", None),
            "max_tokens": getattr(proposal, "max_tokens", None),
            "analysts": list(getattr(proposal, "analysts", []) or []),
            "prompt_version": getattr(proposal, "prompt_version", None),
            "prompt_hash": getattr(proposal, "prompt_hash", None),
            "strategy_version": getattr(proposal, "strategy_version", "1.0.0") or "1.0.0",
            "system_version": getattr(proposal, "system_version", "1.0.0") or "1.0.0",
            "data_source_metadata": clean_ds,
        }
        meta.setdefault("version_metadata", ver_meta)
        for vk, vv in ver_meta.items():
            if vv is not None and vk not in meta:
                meta[vk] = vv

        return cls(
            proposal_id=pid,
            proposal_payload=proposal.model_dump(mode="json"),
            pair=proposal.pair,
            action=proposal.action,
            order_type=proposal.order_type,
            setup_type=proposal.setup_type,
            timeframe=proposal.timeframe,
            entry_price=proposal.entry_price,
            entry_zone_low=proposal.entry_zone_low,
            entry_zone_high=proposal.entry_zone_high,
            stop_loss=proposal.stop_loss,
            take_profit_1=proposal.take_profit_1,
            take_profit_2=proposal.take_profit_2,
            risk_reward_ratio=proposal.risk_reward_ratio,
            sl_pips=proposal.sl_pips,
            tp_pips=proposal.tp_pips,
            suggested_risk_percent=proposal.suggested_risk_percent,
            suggested_lot_size=proposal.suggested_lot_size,
            confluence_factors=proposal.confluence_factors,
            invalidation_condition=proposal.invalidation_condition,
            confidence=getattr(proposal, "confidence", None) if getattr(proposal, "confidence", None) is not None else meta.get("confidence"),
            reasoning=proposal.reasoning,
            trade_rationale_summary=proposal.trade_rationale_summary,
            status=status,
            risk_decision=rd_dict,
            metadata=meta,
            provider=getattr(proposal, "provider", None),
            quick_model=getattr(proposal, "quick_model", None),
            deep_model=getattr(proposal, "deep_model", None),
            temperature=getattr(proposal, "temperature", None),
            reasoning_effort=getattr(proposal, "reasoning_effort", None),
            max_tokens=getattr(proposal, "max_tokens", None),
            analysts=list(getattr(proposal, "analysts", []) or []),
            prompt_version=getattr(proposal, "prompt_version", None),
            prompt_hash=getattr(proposal, "prompt_hash", None),
            strategy_version=getattr(proposal, "strategy_version", "1.0.0") or "1.0.0",
            system_version=getattr(proposal, "system_version", "1.0.0") or "1.0.0",
            data_source_metadata=clean_ds,
        )


