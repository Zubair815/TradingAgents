"""Data models for SQLite trade journal, proposals, executions, and strategy versioning (Phase 12).

Provides typed representations for:
- ProposalRecord: Complete immutable record of ForexTraderProposal + ForexRiskDecision.
- TradeJournalRecord: Complete lifecycle representation of an executed Forex trade.
- OrderExecutionRecord: Broker fill/deal details (MT5 deals, execution slippage, spreads).
- StrategyVersionRecord: Tracking prompt version, model name, and strategy parameters.
"""

