class ProposalStatus(str, Enum):
    """Lifecycle status of a Forex trade proposal."""

    CREATED = "CREATED"             # Initialized proposal draft
    PROPOSED = "PROPOSED"           # Generated by ForexTrader agent
    APPROVED = "APPROVED"           # Cleared by ForexRiskEngine
    MODIFIED = "MODIFIED"           # Approved with mandatory adjustments
    REJECTED = "REJECTED"           # Denied by ForexRiskEngine
    RISK_REJECTED = "RISK_REJECTED" # Denied specifically by ForexRiskEngine
    WAITING_USER = "WAITING_USER"   # Awaiting trader review/action
    EXECUTED = "EXECUTED"           # Logged as executed (workflow intent or broker match)
    SKIPPED = "SKIPPED"             # Explicitly skipped by user
    SKIPPED_BY_USER = "SKIPPED_BY_USER" # Explicitly skipped by user (Phase 17)
    EXPIRED = "EXPIRED"             # Validity window lapsed without execution
    INVALIDATED = "INVALIDATED"     # Market structure / condition invalidated
    SUPERSEDED = "SUPERSEDED"       # Replaced by newer analysis for same pair
    CANCELLED = "CANCELLED"         # Manually or conditionally cancelled

    @classmethod
    def from_str(cls, val: Any) -> ProposalStatus:
        if isinstance(val, ProposalStatus):
            return val
        s = str(val).strip().upper()
        if s == "WAIT":
            return cls.WAITING_USER
        if s == "RISK_REJECTED":
            return cls.RISK_REJECTED
        if s == "SKIPPED_BY_USER":
            return cls.SKIPPED_BY_USER
        if s in ("SKIPPED", "SKIP"):
            return cls.SKIPPED
        for member in cls:
            if member.value == s or member.name == s:
                return member
        return cls.PROPOSED


class TradeStatus(str, Enum):
    """Lifecycle status of an active or settled trade."""

    OPEN = "OPEN"
    CLOSED = "CLOSED"
    CANCELLED = "CANCELLED"

    @classmethod
    def from_str(cls, val: Any) -> TradeStatus:
        if isinstance(val, TradeStatus):
            return val
        s = str(val).strip().upper()
        for member in cls:
            if member.value == s:
                return member
        return cls.OPEN


class TradeExitReason(str, Enum):
    """Reason for closing an executed Forex position."""

    TAKE_PROFIT = "TAKE_PROFIT"
    STOP_LOSS = "STOP_LOSS"
    TRAILING_STOP = "TRAILING_STOP"
    MANUAL = "MANUAL"
    TIME_EXIT = "TIME_EXIT"
    NEWS_EVENT = "NEWS_EVENT"
    INVALIDATION = "INVALIDATION"
    AMBIGUOUS = "AMBIGUOUS"

    @classmethod
    def from_str(cls, val: Any) -> TradeExitReason | None:
        if val is None:
            return None
        if isinstance(val, TradeExitReason):
            return val
        s = str(val).strip().upper()
        if "AMBIGUOUS" in s:
            return cls.AMBIGUOUS
        for member in cls:
            if member.value == s:
                return member
        return cls.MANUAL


